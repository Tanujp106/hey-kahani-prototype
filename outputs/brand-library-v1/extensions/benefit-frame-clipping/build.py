"""Generate nine alpha slices matching each card's border-image: 110 fill.
The same SVG geometry and border inset define both paint and clipping.
"""
from pathlib import Path
from urllib.parse import quote
import xml.etree.ElementTree as ET
ROOT = Path(__file__).resolve().parents[4]
FRAMES = {'screen':'quiet-tide','hands':'double-hill','home':'soft-postcard','simple':'plump-panel-parrot'}
SLICES = [(0,0,110,110),(110,0,420,110),(530,0,110,110),(0,110,110,180),(110,110,420,180),(530,110,110,180),(0,290,110,110),(110,290,420,110),(530,290,110,110)]
lines = ['/* Generated by outputs/brand-library-v1/extensions/benefit-frame-clipping/build.py. */']
for kind,name in FRAMES.items():
    source = ROOT/'shopify-homepage/assets/images/brand-library/containers'/('benefit-'+name+'.svg')
    tree = ET.fromstring(source.read_text())
    paths = ''.join('<path d="'+p.attrib['d']+'" fill="white"/>' for p in tree.iter() if p.tag.endswith('path'))
    images=[]
    for x,y,w,h in SLICES:
        svg=f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}" width="{w}" height="{h}" preserveAspectRatio="none">{paths}</svg>'
        images.append('url("data:image/svg+xml,'+quote(svg,safe='')+'")')
    lines.append('.hk-how-panel--'+kind+' {\n  --hk-benefit-clip: '+',\n    '.join(images)+';\n}')
target=ROOT/'shopify-homepage/assets/css/benefit-frame-masks.css'
target.write_text('\n\n'.join(lines)+'\n')
print('Generated matching masks for four card frames.')
